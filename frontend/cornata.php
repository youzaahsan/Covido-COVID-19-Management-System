                  <h2>What is Coronavirus (COVID-19)?</h2>
  <p>

Coronavirus refers to a large family of viruses that can cause illnesses ranging from the common cold to more severe diseases. In late 2019, a new strain called SARS-CoV-2 emerged in Wuhan, China, causing a disease named COVID-19. This virus quickly spread worldwide, leading to a global pandemic.

COVID-19 mainly spreads through respiratory droplets from coughs, sneezes, or close contact with infected individuals. It can also spread by touching contaminated surfaces and then touching the face. Common symptoms include fever, cough, fatigue, and loss of taste or smell, while severe cases can lead to pneumonia, difficulty breathing, and even death.

Older adults and people with underlying health conditions are at higher risk of severe illness. To fight the virus, scientists developed vaccines such as Pfizer, Moderna, and AstraZeneca, which have proven effective in reducing severe disease and hospitalization. Booster shots are also recommended to maintain immunity, especially with the emergence of new variants.

Preventive measures include wearing masks, hand hygiene, social distancing, and avoiding crowded places. Governments and health organizations continue to monitor and respond to the evolving situation. Public cooperation plays a crucial role in controlling the spread and protecting communities.

                     
